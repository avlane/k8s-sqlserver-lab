#!/usr/bin/env python3
"""Cross-file consistency checks for the lab manifests (text level, standard library only).

This is not a YAML parser. It reads the manifests line by line and checks references that are easy
to get wrong by hand: Secret and ConfigMap names, PVC names, Service selectors, CronJob settings,
image tags. Run from anywhere: python3 scripts/check_lab.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def split_documents(text):
    docs, current = [], []
    for line in text.splitlines():
        if line.startswith("---"):
            docs.append(current)
            current = []
        else:
            current.append(line)
    docs.append(current)
    return [d for d in docs if any(l.strip() and not l.lstrip().startswith("#") for l in d)]


def kind_and_name(doc):
    kind = next((m.group(1) for l in doc if (m := re.match(r"kind:\s*(\S+)", l))), None)
    name = None
    in_meta = False
    for line in doc:
        if line.startswith("metadata:"):
            in_meta = True
        elif in_meta and re.match(r"  name:\s*(\S+)", line):
            name = re.match(r"  name:\s*(\S+)", line).group(1)
            break
        elif in_meta and re.match(r"\S", line):
            break
    return kind, name


def mapping_under(doc, header):
    """Return {key: value} for the lines indented under the first line matching header."""
    result = {}
    for index, line in enumerate(doc):
        if re.match(header, line):
            base = len(line) - len(line.lstrip())
            for nxt in doc[index + 1:]:
                if not nxt.strip():
                    continue
                indent = len(nxt) - len(nxt.lstrip())
                if indent <= base:
                    break
                m = re.match(r"\s+([\w./-]+):\s*\"?([^\"\s]+)\"?\s*$", nxt)
                if m:
                    result[m.group(1)] = m.group(2)
            break
    return result


def load(paths):
    loaded = []
    for path in paths:
        for doc in split_documents(path.read_text()):
            kind, name = kind_and_name(doc)
            loaded.append((path, kind, name, doc))
    return loaded


def check(root):
    problems = []
    files = sorted((root / "manifests").glob("*.yaml"))
    docs = load(files)
    secrets = {}
    for path, kind, name, doc in docs:
        if kind == "Secret":
            secrets[name] = set(mapping_under(doc, r"stringData:")) | set(mapping_under(doc, r"data:"))
    generated = set(re.findall(r"^\s*-\s*name:\s*(\S+)", (root / "kustomization.yaml").read_text(), re.M))
    claims = {name for _, kind, name, _ in docs if kind == "PersistentVolumeClaim"}
    tag_match = re.search(r"newTag:\s*(\S+)", (root / "kustomization.yaml").read_text())
    pinned_tag = tag_match.group(1) if tag_match else None

    for path, kind, name, doc in docs:
        text = "\n".join(doc)
        where = "{} ({}/{})".format(path.name, kind, name)
        for m in re.finditer(r"secretKeyRef:\s*\n\s+name:\s*(\S+)\s*\n\s+key:\s*(\S+)", text):
            secret, key = m.groups()
            if secret not in secrets:
                problems.append("{}: secretKeyRef to unknown Secret {}".format(where, secret))
            elif key not in secrets[secret]:
                problems.append("{}: Secret {} has no key {}".format(where, secret, key))
        for m in re.finditer(r"configMap:\s*\n\s+name:\s*(\S+)", text):
            if m.group(1) not in generated:
                problems.append("{}: configMap {} is not generated by kustomization.yaml".format(where, m.group(1)))
        for m in re.finditer(r"claimName:\s*(\S+)", text):
            if m.group(1) not in claims:
                problems.append("{}: claimName {} has no PersistentVolumeClaim manifest".format(where, m.group(1)))
        for m in re.finditer(r"image:\s*(\S+)", text):
            image = m.group(1)
            if ":" not in image.split("/")[-1] or image.endswith(":latest"):
                problems.append("{}: image {} is not pinned to a tag".format(where, image))
            elif image.startswith("mcr.microsoft.com/mssql/server:") and pinned_tag and image.split(":")[-1] != pinned_tag:
                # kustomize overrides the tag, but a plain `kubectl apply -f` of this file would not
                problems.append("{}: image tag {} differs from the kustomization newTag {}".format(
                    where, image.split(":")[-1], pinned_tag))
        if kind == "CronJob" and "concurrencyPolicy:" not in text:
            problems.append("{}: CronJob without concurrencyPolicy".format(where))
        if kind == "CronJob" and "timeZone:" not in text:
            problems.append("{}: CronJob without timeZone".format(where))

    # Service selectors must be a subset of the StatefulSet Pod labels
    pod_labels = {}
    for path, kind, name, doc in docs:
        if kind == "StatefulSet":
            pod_labels.update(mapping_under(doc, r"  template:"))
            template = "\n".join(doc)
            m = re.search(r"template:\s*\n\s+metadata:\s*\n\s+labels:\s*\n((?:\s+[\w./-]+:\s*\S+\n)+)", template)
            if m:
                pod_labels = dict(re.findall(r"([\w./-]+):\s*(\S+)", m.group(1)))
    for path, kind, name, doc in docs:
        if kind == "Service":
            selector = mapping_under(doc, r"  selector:")
            for key, value in selector.items():
                if pod_labels.get(key) != value:
                    problems.append("{}.yaml: Service {} selects {}={} which the StatefulSet Pod does not have".format(
                        path.stem, name, key, value))
    return problems


def main():
    problems = check(ROOT)
    for problem in problems:
        print(problem)
    print("{} problem(s)".format(len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
